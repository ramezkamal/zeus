const I18nContext = createContext({ lang: "ar", t: (k) => k, setLang: () => {}, dir: "rtl" });

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("zeus_lang") || "ar");
  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    localStorage.setItem("zeus_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const t = (key) => (dict[lang] && dict[lang][key]) || dict.ar[key] || key;
  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);